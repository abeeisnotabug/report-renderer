// Renders a Markdown file with LaTeX maths to one self-contained HTML page, the only output.
// Usage: render.sh some-folder/some-file.md  -> writes some-file.html next to it.
// Maths is rendered by KaTeX here, not in the browser, and the KaTeX fonts are embedded, so the
// page works offline. Display formulas are regrouped by breaks.mjs, so the reader's browser breaks
// them by fixed rules (STYLE.md); nothing is measured and no browser runs here.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import vm from 'node:vm';
const require = createRequire(import.meta.url);
const katex = require('katex');
import * as breaks from './breaks.mjs';
import { check as listCheck } from './listcheck.mjs';

const md = path.resolve(process.argv[2]);
const base = md.replace(/\.md$/, '');
const pandoc = process.env.PANDOC || 'pandoc';
const here = path.dirname(fileURLToPath(import.meta.url));
// Wrapped lines that would start a list by accident (listcheck.mjs): a warning, not an error
for (const w of listCheck(fs.readFileSync(md, 'utf8'))) console.warn('warning: ' + path.basename(md) + ', ' + w);
// layers.lua folds sections, items and R code, but only in documents with `layered: true`
let body = execFileSync(pandoc, ['-f', 'markdown', '-t', 'html5', '--math-method=katex', '--wrap=none',
  '--lua-filter', path.join(here, 'layers.lua'), md], { encoding: 'utf8', maxBuffer: 512 * 1024 * 1024 });  // long pages exceed the default buffer
const layered = body.includes('id="layer-toolbar"');

const unesc = s => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');
let nMath = 0;
// Punctuation right after an inline formula (. , ; : ! ? ) ]) is rendered as text inside the
// formula, so it stays on the line of the formula's last piece; the formula can still break
// after = or + inside it. Without this the browser may start a line with the comma.
body = body.replace(/<span class="math (inline|display)">([\s\S]*?)<\/span>([.,;:!?)\]]*)/g, (m, kind, tex, punct) => {
  nMath++;
  if (kind === 'display') return breaks.render(unesc(tex)) + punct;
  return katex.renderToString(unesc(tex) + (punct ? `\\text{${punct}}` : ''), { throwOnError: true, output: 'html' });
});
if (/class="math /.test(body)) throw new Error('unrendered math left');

// Embed local images (e.g. knitr figures) as data URIs, so the HTML stays self-contained
body = body.replace(/<img([^>]*?) src="([^"]+)"/g, (m, pre, src) => {
  if (/^(data:|https?:)/.test(src)) return m;
  const f = path.resolve(path.dirname(md), decodeURI(src));
  const mime = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.svg': 'image/svg+xml' }[path.extname(f).toLowerCase()];
  if (!mime || !fs.existsSync(f)) throw new Error('image not found or unknown type: ' + src);
  // STYLE.md, "Figures and plots": a plot over 500 KB gets its heavy layer rasterised
  const kb = fs.statSync(f).size / 1024;
  if (kb > 500) console.warn(`warning: ${path.basename(md)}, image ${src} is ${Math.round(kb)} KB (over 500 KB): rasterise its heavy layer, ggrastr::rasterise(..., dpi = 220)`);
  // A TikZ figure (tikz2svg.sh, made by dvisvgm) is sized in em, so that its 10 pt labels show at
  // the size of the text (KaTeX_Main, the same Computer Modern), and it gets class "tikz". A plot
  // made by svglite gets class "plot". Both follow dark mode. The width is capped at the column.
  let extra = '';
  if (mime === 'image/svg+xml') {
    const head = fs.readFileSync(f, 'utf8').slice(0, 600);
    const w = head.match(/<svg[^>]*\swidth='([\d.]+)pt'/);
    if (/generated by dvisvgm/.test(head) && w) extra = ` class="tikz" style="width:${(w[1] / 10).toFixed(2)}em"`;
    else if (/class='svglite'/.test(head)) extra = ' class="plot"';
  }
  return `<img${pre}${extra} src="data:${mime};base64,${fs.readFileSync(f).toString('base64')}"`;
});

// Interactive figures (layers.lua, livefig.js): each figure is followed by a placeholder script
// naming its file. The file (path relative to the .md) replaces the placeholder, as the body of a
// function that receives the figure's host element and the library: LiveFig.run(id, (host, L) => ...).
// A missing file or a syntax error stops the build with the file's name. A literal colour in a
// script is a warning: figures use theme colours only (STYLE.md, "Interactive figures").
const liveRe = /<script type="text\/x-livefig" data-fig="([^"]*)" data-src="([^"]*)"><\/script>/g;
let nLive = 0;
body = body.replace(liveRe, (m, fig, src) => {
  nLive++;
  fig = unesc(fig); src = unesc(src);
  const f = path.resolve(path.dirname(md), src);
  if (!fs.existsSync(f)) throw new Error('interactive figure #' + fig + ': script not found: ' + src);
  const code = fs.readFileSync(f, 'utf8');
  // (the wrapper's start shares the file's first line, so that line numbers in errors match the file)
  const wrapped = 'LiveFig.run(' + JSON.stringify(fig) + ', function (host, L) { ' + code + '\n});';
  try { new vm.Script(wrapped, { filename: f }); }
  catch (e) { throw new Error('interactive figure #' + fig + ', ' + src + ': ' + e.message + ' (' + (e.stack || '').split('\n')[0] + ')'); }
  const bare = code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
  if (/#[0-9a-fA-F]{3,8}\b|\b(rgba?|hsla?)\(/.test(bare)) console.warn('warning: ' + src + ' has a literal colour; use theme colours (a to f, fg, muted, rule, bg)');
  // "</script" or "<!--" inside the code would end or confuse the script element
  return '<script>' + wrapped.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--') + '</script>';
});

// KaTeX CSS with woff2 fonts inlined, other formats dropped
const kdir = path.dirname(require.resolve('katex/dist/katex.min.css'));
let kcss = fs.readFileSync(path.join(kdir, 'katex.min.css'), 'utf8');
kcss = kcss.replace(/src:url\((fonts\/[^)]+\.woff2)\) format\("woff2"\)(,url\([^)]+\) format\("[^"]+"\))*/g, (m, f) =>
  `src:url(data:font/woff2;base64,${fs.readFileSync(path.join(kdir, f)).toString('base64')}) format("woff2")`);

